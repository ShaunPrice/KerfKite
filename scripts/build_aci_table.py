"""Write native/core/src/aci_colors.hpp: the AutoCAD Color Index, the 256 colours a DXF layer names by number.

The palette is AutoCAD's standard one, the colours CAD programs show for colour numbers 1 to 255. The native
core's DXF reader gives a layer the colour Studio's Python reader gives it, so the table is taken, as data,
from the palette the Python reader uses (ezdxf.colors.DXF_DEFAULT_COLORS) on the machine that writes it.
ezdxf is a development tool here, not a dependency of the core. Run:

    python scripts/build_aci_table.py
"""

from pathlib import Path

from ezdxf import __version__, colors

OUT = Path(__file__).resolve().parent.parent / 'native' / 'core' / 'src' / 'aci_colors.hpp'


def main():
    palette = list(colors.DXF_DEFAULT_COLORS)
    if len(palette) != 256:
        raise SystemExit('The palette does not have 256 colours')
    rows = [', '.join(f'0x{value:06X}' for value in palette[i : i + 8]) for i in range(0, 256, 8)]
    body = ',\n    '.join(rows)
    OUT.write_text(
        f'''// Generated by scripts/build_aci_table.py from the AutoCAD Color Index palette (as ezdxf {__version__} holds it).
// Do not edit. kAciColors[n] is colour number n as 0xRRGGBB; 0 and 256 have no colour of their own.
#ifndef KERFKITE_ACI_COLORS_HPP
#define KERFKITE_ACI_COLORS_HPP

#include <cstdint>

namespace kerfkite {{

const std::uint32_t kAciColors[256] = {{
    {body}}};

}}  // namespace kerfkite

#endif
''',
        encoding='utf-8',
    )
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
