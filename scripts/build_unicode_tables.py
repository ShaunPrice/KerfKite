"""Write native/core/src/unicode_tables.hpp: the facts about characters the native core reads text by.

The reference reads CAD scripts, foreign drawings and programs with Python's str methods and re module, and
reports a character it cannot read with repr(), so the native core needs, for every code point, what the
Unicode Character Database says in the Python that wrote the table:

* whether it is a decimal digit (general category Nd), which the pattern \\d matches and float() reads;
* whether str.isprintable() is true of it, which decides whether repr() shows it or escapes it;
* what str.upper() makes of it (one to three code points);
* whether the pattern \\w matches it (str.isalnum() or the underscore).

The table is generated, not written by hand, so that it is exactly the database of one Python release. The
release is named in the header. Run with the Python whose behaviour the core should match:

    python scripts/build_unicode_tables.py
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / 'native' / 'core' / 'src' / 'unicode_tables.hpp'


def runs(test):
    """(first, last) of each run of code points for which test is true."""
    found, start = [], None
    for code in range(0x110000):
        if test(code):
            if start is None:
                start = code
        elif start is not None:
            found.append((start, code - 1))
            start = None
    if start is not None:
        found.append((start, 0x10FFFF))
    return found


def rows(pairs, per_row=4):
    text = [f'{{0x{a:X}, 0x{b:X}}}' for a, b in pairs]
    return ',\n'.join('    ' + ', '.join(text[i : i + per_row]) for i in range(0, len(text), per_row))


def main():
    digits = [code for code in range(0x110000) if unicodedata.decimal(chr(code), -1) == 0]
    for start in digits:
        if any(unicodedata.decimal(chr(start + k), -1) != k for k in range(10)):
            raise SystemExit(f'Decimal digits from U+{start:04X} are not a run of ten')
    if sum(1 for code in range(0x110000) if unicodedata.decimal(chr(code), -1) >= 0) != 10 * len(digits):
        raise SystemExit('A decimal digit lies outside the runs of ten')
    hidden = runs(lambda code: not chr(code).isprintable())
    word = runs(lambda code: chr(code).isalnum() or chr(code) == '_')
    uppers = []
    for code in range(0x110000):
        mapped = chr(code).upper()
        if mapped != chr(code):
            if len(mapped) > 3:
                raise SystemExit(f'str.upper() of U+{code:04X} is longer than three code points')
            uppers.append([code, *map(ord, mapped), *[0] * (3 - len(mapped))])
    upper_rows = ',\n'.join(
        '    ' + ', '.join('{' + ', '.join(f'0x{c:X}' for c in row) + '}' for row in uppers[i : i + 3])
        for i in range(0, len(uppers), 3)
    )
    starts = ',\n'.join('    ' + ', '.join(f'0x{c:X}' for c in digits[i : i + 8]) for i in range(0, len(digits), 8))
    version = '.'.join(map(str, sys.version_info[:2]))
    OUT.write_text(
        f"""// Generated by scripts/build_unicode_tables.py from the Unicode Character Database {unicodedata.unidata_version}
// of Python {version}. Do not edit.
//
// What the core needs to read text as Python's str methods and re module do and to report a character
// as repr() does: the decimal digits, the characters str.isprintable() is false of, str.upper() and the
// characters \\w matches.
#ifndef KERFKITE_UNICODE_TABLES_HPP
#define KERFKITE_UNICODE_TABLES_HPP

#include <cstdint>

namespace kerfkite {{
namespace detail {{

// The first code point of each run of ten decimal digits (general category Nd), zero to nine.
static const uint32_t kDecimalDigitRuns[] = {{
{starts}
}};

// The runs of code points that str.isprintable() is false of, in order.
static const uint32_t kNotPrintable[][2] = {{
{rows(hidden)}
}};

// str.upper() of each code point it changes, in order: the code point, then the one to three it becomes
// (0 after the last).
static const uint32_t kUpper[][4] = {{
{upper_rows}
}};

// The runs of code points the pattern \\w matches (str.isalnum(), and the underscore), in order.
static const uint32_t kWordRuns[][2] = {{
{rows(word)}
}};

}}  // namespace detail
}}  // namespace kerfkite

#endif
""",
        encoding='utf-8',
    )
    print(
        f'{OUT.name}: {len(digits)} runs of digits, {len(hidden)} runs that are not printable,'
        f' {len(uppers)} upper-case mappings, {len(word)} runs of word characters'
    )


if __name__ == '__main__':
    main()
