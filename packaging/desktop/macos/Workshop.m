- (void)invoke:(NSString *)action payload:(NSDictionary *)payload reply:(KKReply)reply {
    if (![self trusted:self.web.URL]) { reply(nil,@"The local workstation is unavailable."); return; }
    NSData *json = [NSJSONSerialization dataWithJSONObject:@[action,payload ?: @{}] options:0 error:nil];
    NSString *args = [[NSString alloc] initWithData:json encoding:NSUTF8StringEncoding];
    NSString *script = [NSString stringWithFormat:@"window.KerfKiteDesktop?.dispatch(...%@)",args];
    [self.web evaluateJavaScript:script inFrame:nil inContentWorld:WKContentWorld.pageWorld completionHandler:^(id raw,NSError *error){
        if (![self trusted:self.web.URL] || error || ![raw isKindOfClass:NSString.class]) {
            reply(nil,@"The workstation editor is unavailable."); return;
        }
        id result = [NSJSONSerialization JSONObjectWithData:[raw dataUsingEncoding:NSUTF8StringEncoding] options:0 error:nil];
        if (![result isKindOfClass:NSDictionary.class] || ![result[@"ok"] boolValue]) {
            NSString *reason = [result isKindOfClass:NSDictionary.class] ? result[@"error"] : nil;
            reply(nil,[reason isKindOfClass:NSString.class] ? reason : @"The editor returned an invalid result."); return;
        }
        NSNumber *pending = result[@"pending"];
        if ([pending isKindOfClass:NSNumber.class]) {
            dispatch_after(dispatch_time(DISPATCH_TIME_NOW, NSEC_PER_MSEC*80), dispatch_get_main_queue(), ^{
                [self invoke:@"result" payload:@{@"id":pending} reply:reply];
            });
        } else reply(result[@"value"],nil);
    }];
}
- (void)poll {
    if (self.busy || self.polling || ![self trusted:self.web.URL]) return;
    self.polling = YES;
    [self invoke:@"state" payload:nil reply:^(id value, NSString *error){
        self.polling = NO; if (![value isKindOfClass:NSDictionary.class] || error) return;
        [self applyState:value];
    }];
}
- (void)applyState:(NSDictionary *)state {
    if (!self.ready) { self.ready = YES; self.wasReady = YES; self.retryButton.hidden = YES; [self notice:@"Local workstation ready"]; }
    if (![self.fileDocumentId isEqual:state[@"documentId"]]) self.documentURL = nil;
    self.dirty = [state[@"dirty"] boolValue]; self.window.documentEdited = self.dirty;
    self.window.title = [NSString stringWithFormat:@"%@ — KerfKite",state[@"title"] ?: @"Untitled project"];
    self.refreshing = YES;
    NSArray *objects = state[@"objects"]; if (![objects isKindOfClass:NSArray.class]) objects = @[];
    if (![objects isEqual:self.objects]) { self.objects = objects; [self.table reloadData]; }
    NSInteger index = [state[@"selected"] integerValue];
    NSUInteger row = [objects indexOfObjectPassingTest:^BOOL(NSDictionary *o,NSUInteger i,BOOL *stop){ return [o[@"index"] integerValue] == index; }];
    if (row != NSNotFound && (NSInteger)row != self.table.selectedRow)
        [self.table selectRowIndexes:[NSIndexSet indexSetWithIndex:row] byExtendingSelection:NO];
    else if (row == NSNotFound) [self.table deselectAll:self];
    NSDictionary *selection = [state[@"selection"] isKindOfClass:NSDictionary.class] ? state[@"selection"] : nil;
    if (selection && (index != self.lastIndex || ![selection isEqual:self.lastSelection])) {
        NSArray *keys = @[@"x",@"y",@"width",@"height"];
        for (NSUInteger i = 0; i < keys.count; i++) {
            NSNumber *n = selection[keys[i]];
            if ([n isKindOfClass:NSNumber.class] && !self.fields[i].currentEditor)
                self.fields[i].stringValue = [NSString stringWithFormat:@"%.6g",n.doubleValue];
        }
    }
    self.lastSelection = selection; self.lastIndex = index; self.moveButton.enabled = selection != nil;
    if ([state[@"tab"] isKindOfClass:NSString.class]) [self.workspace selectItemWithTitle:state[@"tab"]];
    self.refreshing = NO;
}
- (void)perform:(NSString *)action payload:(NSDictionary *)payload {
    if (self.busy || self.closing || self.window.attachedSheet) return;
    self.busy = YES;
    [self invoke:action payload:payload reply:^(id value, NSString *error){
        self.busy = NO; if (error) [self notice:error]; else if ([action isEqual:@"preview"]) [self notice:@"Toolpath preview updated"];
        [self poll];
    }];
}
