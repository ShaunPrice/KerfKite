- (void)downloadDidFinish:(WKDownload *)download {
    NSValue *key = [NSValue valueWithNonretainedObject:download]; NSDictionary *pair = self.downloads[key];
    if (!pair) return; NSError *e = nil; NSURL *stage = pair[@"stage"], *dest = pair[@"dest"]; NSFileManager *fm = NSFileManager.defaultManager;
    if ([fm fileExistsAtPath:dest.path]) [fm replaceItemAtURL:dest withItemAtURL:stage backupItemName:nil options:0 resultingItemURL:nil error:&e];
