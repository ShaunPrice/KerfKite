- (void)openDocument:(NSURL *)url {
    NSNumber *bytes = nil, *regular = nil;
    [url getResourceValue:&bytes forKey:NSURLFileSizeKey error:nil];
    [url getResourceValue:&regular forKey:NSURLIsRegularFileKey error:nil];
    if (!regular.boolValue || !bytes || bytes.unsignedLongLongValue > 4000000) { [self notice:@"Choose a project file of up to 4 MB."]; return; }
    NSError *error = nil; NSData *data = [NSData dataWithContentsOfURL:url options:NSDataReadingMappedIfSafe error:&error];
    NSString *content = data.length <= 4000000 ? (data ? [[NSString alloc] initWithData:data encoding:NSUTF8StringEncoding] : nil) : nil;
    if (!content || !data) { [self notice:error.localizedDescription ?: @"The project must contain UTF-8 JSON of up to 4 MB."]; return; }
    [self confirmClosing:^(BOOL discard){ if (discard) {
        self.busy = YES; [self invoke:@"open" payload:@{@"content":content} reply:^(NSDictionary *state,NSString *reason){
            self.busy = NO;
            if (reason) { [self notice:reason]; return; }
            self.documentURL = url; self.fileDocumentId = state[@"documentId"]; [self applyState:state];
            [self notice:[@"Opened " stringByAppendingString:url.lastPathComponent]];
        }];
    } }];
}
