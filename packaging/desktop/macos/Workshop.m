NSURL *KKWorkshopURL(NSString *s) {
    NSURLComponents *c = [NSURLComponents componentsWithString:s];
    if (![c.scheme isEqual:@"http"] || ![c.host isEqual:@"127.0.0.1"] || !c.port ||
        c.port.integerValue < 1 || c.port.integerValue > 65535 || c.user || c.password ||
        c.query || c.fragment || !(c.path.length == 0 || [c.path isEqual:@"/"])) return nil;
    // Reject encoded hostnames, ports with leading zeros, extra slashes, and URL parser disagreements.
    NSString *origin = [NSString stringWithFormat:@"http://127.0.0.1:%@", c.port];
    NSString *address = [origin stringByAppendingString:@"/"];
    return ([s isEqual:origin] || [s isEqual:address]) ? [NSURL URLWithString:address] : nil;
}

static BOOL BlankPrintLink(NSURL *url) { return !url.absoluteString.length || [url.absoluteString isEqual:@"about:blank"]; }

