- (void)webView:(WKWebView *)w decidePolicyForNavigationAction:(WKNavigationAction *)a decisionHandler:(void (^)(WKNavigationActionPolicy))done {
    NSURL *u = a.request.URL;
    if (!a.targetFrame && BlankPrintLink(u) && [self trustedSource:a]) { done(WKNavigationActionPolicyAllow); return; }
    if (a.shouldPerformDownload && [self trustedSource:a] &&
        ([self trusted:u] || ([u.scheme isEqual:@"blob"] && [u.absoluteString hasPrefix:[@"blob:" stringByAppendingString:self.baseURL.absoluteString]]))) {
        done(WKNavigationActionPolicyDownload); return;
    }
    if (a.targetFrame.isMainFrame && [self trusted:u]) { done(WKNavigationActionPolicyAllow); return; }
    if (a.navigationType == WKNavigationTypeLinkActivated && [self trustedSource:a] &&
        ([u.scheme isEqual:@"https"] || [u.scheme isEqual:@"http"])) [self openLink:u];
    done(WKNavigationActionPolicyCancel);
}
