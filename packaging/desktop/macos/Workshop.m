- (void)chooseDestination:(NSString *)action alwaysAsk:(BOOL)alwaysAsk {
    if (self.busy || self.window.attachedSheet) return;
    self.busy = YES;
    [self invoke:action payload:nil reply:^(NSDictionary *artifact,NSString *error){
        if (error || ![artifact isKindOfClass:NSDictionary.class] || ![artifact[@"content"] isKindOfClass:NSString.class] ||
            ![artifact[@"name"] isKindOfClass:NSString.class]) { self.busy = NO; [self notice:error ?: @"This export is unavailable."]; return; }
        NSNumber *identity = artifact[@"documentId"];
        if (!alwaysAsk && self.documentURL && identity && [self.fileDocumentId isEqual:identity]) {
            [self writeContent:artifact[@"content"] toURL:self.documentURL project:YES]; return;
        }
        NSSavePanel *p = [NSSavePanel savePanel]; p.nameFieldStringValue = [artifact[@"name"] lastPathComponent];
        p.title = [action isEqual:@"save"] ? @"Save KerfKite Project" : @"Export G-code";
        [p beginSheetModalForWindow:self.window completionHandler:^(NSModalResponse r){
            if (r != NSModalResponseOK) { self.busy = NO; return; }
            [self writeContent:artifact[@"content"] toURL:p.URL project:[action isEqual:@"save"]];
        }];
    }];
