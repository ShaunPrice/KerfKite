- (BOOL)trusted:(NSURL *)url {
    if (!url) return NO;
    NSURLComponents *c = [NSURLComponents componentsWithURL:url resolvingAgainstBaseURL:YES]; c.fragment = nil;
    return [[KKWorkshopURL(c.string) absoluteString] isEqual:self.baseURL.absoluteString];
}
