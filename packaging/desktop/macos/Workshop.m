- (NSDictionary *)geometry:(BOOL)size {
    NSMutableDictionary *result = [NSMutableDictionary new]; NSArray *keys = @[@"x",@"y",@"width",@"height"];
    for (NSUInteger i = 0; i < (size ? 4 : 2); i++) {
        NSString *text = [self.fields[i].stringValue stringByTrimmingCharactersInSet:NSCharacterSet.whitespaceAndNewlineCharacterSet];
        NSScanner *scanner = [NSScanner scannerWithString:text]; double n;
        if (![scanner scanDouble:&n] || !scanner.isAtEnd || !isfinite(n)) { [self notice:@"Enter a finite number for each dimension in millimetres."]; return nil; }
        result[keys[i]] = @(n);
    }
    return result;
}
