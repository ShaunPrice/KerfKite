# A relief from a 400-point map sent as RGB bytes: every point and depth. The threads change no bit, so it holds
# with any KERFKITE_THREADS; where the computer has a usable GPU, the same job forced onto it must give it too.
rng = random.Random(1024)  # noqa: S311 - a fixed fixture
SIDE = 400
RELIEF = {
    'x': 5,
    'y': 5,
    'width': 120,
    'height': 90,
    'depth': 4,
    'tool_diameter': 6,
    'tool_shape': 'ball',
    'stepover': 1.5,
    'allowance': 0.1,
    'heightmap_size': [SIDE, SIDE],
    'heightmap_rgb': base64.b64encode(bytes(rng.randrange(256) for _ in range(SIDE * SIDE * 3))).decode(),
}


def relief_summary(result):
    text = json.dumps(floats([result['paths'], result['path_depths']]), separators=(',', ':'))
    return len(result['paths']), sum(map(len, result['paths'])), digest(text)


relief = cam('relief', RELIEF)
check('relief paths and depths', relief_summary(relief), (61, 24400, '55a418fdfe4d9ccb'))
check('relief on one thread', relief_summary(cam('relief', RELIEF, env={'KERFKITE_THREADS': '1'})),
      (61, 24400, '55a418fdfe4d9ccb'))  # fmt: skip
forced = cam('relief', RELIEF, env={'KERFKITE_GPU': 'on'})
check(f'relief with the GPU asked for (it ran on the {forced.get("device", "CPU")})', relief_summary(forced),
      (61, 24400, '55a418fdfe4d9ccb'))  # fmt: skip

