def board(command, text, **options):
    """A circuit board command on a Gerber layer, with its options as the command line's --name VALUE pairs."""
    with tempfile.TemporaryDirectory() as folder:
        layer = Path(folder) / 'layer.gbr'
        layer.write_text(text, encoding='ascii')
        arguments = [
            item for name, value in options.items() for item in ('--' + name.replace('_', '-'), json.dumps(value))
        ]
        done = subprocess.run([CAM, command, str(layer), *arguments], capture_output=True, text=True, check=False)  # noqa: S603
    if done.returncode:
        raise AssertionError(f'kerfkite-cam {command} exited {done.returncode}: {done.stderr.strip()[:400]}')
    return json.loads(done.stdout)


